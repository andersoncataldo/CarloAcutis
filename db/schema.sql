-- =================================================================
-- SCHEMA IDEMPOTENTE — CARLO ACUTIS (NEON POSTGRESQL SERVERLESS)
-- -----------------------------------------------------------------
-- Executável repetidamente sem falhas (CREATE IF NOT EXISTS +
-- ON CONFLICT DO NOTHING + sincronização de sequences).
--
-- Como aplicar:
--   npm run db:migrate
--   (ou cole no SQL Editor do Neon / Vercel Storage)
-- =================================================================

-- 1. LIGAS PAROQUIAIS
CREATE TABLE IF NOT EXISTS public.ligas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL CHECK (length(trim(nome)) > 0),
    codigo_acesso VARCHAR(16) NOT NULL UNIQUE,
    criado_por UUID,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 2. USUÁRIOS (autenticação própria com scrypt + perfil + gamificação)
CREATE TABLE IF NOT EXISTS public.users (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    nome VARCHAR(120) NOT NULL DEFAULT 'Peregrino' CHECK (length(trim(nome)) > 0),
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    xp INT NOT NULL DEFAULT 0 CHECK (xp >= 0),
    role VARCHAR(20) NOT NULL DEFAULT 'user' CHECK (role IN ('user', 'admin')),
    liga_id BIGINT REFERENCES public.ligas(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Chave estrangeira circular ligas.criado_por -> users.id (idempotente)
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'fk_ligas_criado_por'
    ) THEN
        ALTER TABLE public.ligas
            ADD CONSTRAINT fk_ligas_criado_por
            FOREIGN KEY (criado_por) REFERENCES public.users(id) ON DELETE SET NULL;
    END IF;
END $$;

-- 3. SESSÕES (cookie HttpOnly -> token_hash SHA-256)
CREATE TABLE IF NOT EXISTS public.sessions (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    token_hash CHAR(64) NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 4. TEMPORADAS DO QUIZ
CREATE TABLE IF NOT EXISTS public.temporadas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(100) NOT NULL CHECK (length(trim(titulo)) > 0),
    descricao TEXT NOT NULL DEFAULT '',
    ordem INT NOT NULL DEFAULT 1,
    ativa BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 5. PERGUNTAS DO QUIZ
CREATE TABLE IF NOT EXISTS public.perguntas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    temporada_id BIGINT NOT NULL REFERENCES public.temporadas(id) ON DELETE CASCADE,
    texto_pergunta VARCHAR(300) NOT NULL CHECK (length(trim(texto_pergunta)) > 0),
    opcao_a VARCHAR(150) NOT NULL CHECK (length(trim(opcao_a)) > 0),
    opcao_b VARCHAR(150) NOT NULL CHECK (length(trim(opcao_b)) > 0),
    opcao_c VARCHAR(150) NOT NULL CHECK (length(trim(opcao_c)) > 0),
    opcao_d VARCHAR(150) NOT NULL CHECK (length(trim(opcao_d)) > 0),
    resposta_correta CHAR(1) NOT NULL CHECK (resposta_correta IN ('A', 'B', 'C', 'D')),
    explicacao TEXT NOT NULL DEFAULT '',
    ordem INT NOT NULL DEFAULT 1,
    ativa BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Garante a coluna explicacao em bancos já existentes (migração idempotente)
ALTER TABLE public.perguntas
    ADD COLUMN IF NOT EXISTS explicacao TEXT NOT NULL DEFAULT '';

-- 6. HISTÓRICO DE RESPOSTAS (único por usuário + pergunta)
CREATE TABLE IF NOT EXISTS public.respostas_usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    pergunta_id BIGINT NOT NULL REFERENCES public.perguntas(id) ON DELETE CASCADE,
    resposta_dada CHAR(1) NOT NULL CHECK (resposta_dada IN ('A', 'B', 'C', 'D')),
    acertou BOOLEAN NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT unique_user_pergunta UNIQUE (user_id, pergunta_id)
);

-- 7. SEQUÊNCIA DIÁRIA (STREAKS)
CREATE TABLE IF NOT EXISTS public.streaks (
    user_id UUID PRIMARY KEY REFERENCES public.users(id) ON DELETE CASCADE,
    streak_atual INT NOT NULL DEFAULT 1 CHECK (streak_atual >= 1),
    maior_streak INT NOT NULL DEFAULT 1 CHECK (maior_streak >= 1),
    ultimo_acesso DATE NOT NULL DEFAULT (timezone('utc', now()))::date,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 8. CONQUISTAS E CONQUISTAS DO USUÁRIO
CREATE TABLE IF NOT EXISTS public.conquistas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(50) NOT NULL UNIQUE,
    nome VARCHAR(120) NOT NULL,
    descricao TEXT NOT NULL DEFAULT '',
    icone VARCHAR(16) NOT NULL DEFAULT '🏅',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.usuario_conquistas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    conquista_id BIGINT NOT NULL REFERENCES public.conquistas(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT unique_user_conquista UNIQUE (user_id, conquista_id)
);

-- 9. AUDITORIA ADMINISTRATIVA
CREATE TABLE IF NOT EXISTS public.auditoria_admin (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id UUID REFERENCES public.users(id) ON DELETE SET NULL,
    acao VARCHAR(30) NOT NULL,
    entidade VARCHAR(50) NOT NULL,
    entidade_id TEXT,
    valores_antigos JSONB,
    valores_novos JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 10. CONTROLE DE TAXA (RATE LIMITING DISTRIBUÍDO — APENAS HASHES SHA-256)
CREATE TABLE IF NOT EXISTS public.rate_limits (
    key TEXT PRIMARY KEY,
    hits INT NOT NULL DEFAULT 1 CHECK (hits >= 1),
    window_start TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- =================================================================
-- ÍNDICES
-- =================================================================
CREATE INDEX IF NOT EXISTS idx_users_liga_xp
    ON public.users (liga_id, xp DESC)
    WHERE liga_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_sessions_user_id
    ON public.sessions (user_id);

CREATE INDEX IF NOT EXISTS idx_sessions_expires_at
    ON public.sessions (expires_at);

CREATE INDEX IF NOT EXISTS idx_ligas_criado_por
    ON public.ligas (criado_por);

CREATE INDEX IF NOT EXISTS idx_temporadas_ativa_ordem
    ON public.temporadas (ativa, ordem, id);

CREATE INDEX IF NOT EXISTS idx_perguntas_temporada_ativa_ordem
    ON public.perguntas (temporada_id, ativa, ordem, id);

CREATE INDEX IF NOT EXISTS idx_respostas_usuario_user_id
    ON public.respostas_usuario (user_id);

CREATE INDEX IF NOT EXISTS idx_usuario_conquistas_user_id
    ON public.usuario_conquistas (user_id);

CREATE INDEX IF NOT EXISTS idx_auditoria_admin_created_at
    ON public.auditoria_admin (created_at DESC);

CREATE INDEX IF NOT EXISTS idx_rate_limits_window_start
    ON public.rate_limits (window_start);

