-- =================================================================
-- 1. CORREÇÃO: "nivel" deixa de ser gravado manualmente e passa a
--    ser uma COLUNA GERADA a partir do xp. Isso elimina de vez o
--    risco de "nivel" ficar desatualizado em relação ao xp (drift),
--    caso as faixas de calcular_titulo mudem no futuro.
-- =================================================================
DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'profiles'
          AND column_name = 'nivel' AND is_generated = 'NEVER'
    ) THEN
        ALTER TABLE public.profiles DROP COLUMN nivel;
        ALTER TABLE public.profiles
            ADD COLUMN nivel VARCHAR(100) GENERATED ALWAYS AS (public.calcular_titulo(xp)) STORED;
    END IF;
END $$;

-- =================================================================
-- 2. CORREÇÃO: sincroniza profiles.email quando o e-mail é alterado
--    em auth.users (hoje só era copiado na criação da conta).
-- =================================================================
CREATE OR REPLACE FUNCTION public.handle_user_updated()
RETURNS TRIGGER AS $$
BEGIN
    IF NEW.email IS DISTINCT FROM OLD.email THEN
        UPDATE public.profiles
        SET email = NEW.email, updated_at = NOW()
