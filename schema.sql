-- RPC chamada no login/abertura do app para atualizar a sequência diária.
CREATE OR REPLACE FUNCTION public.registrar_acesso()
RETURNS JSONB AS $$
DECLARE
    v_user_id UUID;
    v_hoje DATE := (timezone('utc'::text, now()))::date;
    v_ultimo DATE;
    v_atual INT;
    v_maior INT;
BEGIN
    v_user_id := auth.uid();
    IF v_user_id IS NULL THEN
        RAISE EXCEPTION 'Usuário não autenticado.';
    END IF;

    INSERT INTO public.streaks (user_id, streak_atual, maior_streak, ultimo_acesso)
    VALUES (v_user_id, 1, 1, v_hoje)
    ON CONFLICT (user_id) DO NOTHING;

    SELECT ultimo_acesso, streak_atual, maior_streak INTO v_ultimo, v_atual, v_maior
    FROM public.streaks WHERE user_id = v_user_id;

    IF v_ultimo = v_hoje THEN
        -- já registrado hoje, não faz nada
        NULL;
    ELSIF v_ultimo = v_hoje - 1 THEN
        v_atual := v_atual + 1;
        v_maior := GREATEST(v_maior, v_atual);
        UPDATE public.streaks
        SET streak_atual = v_atual, maior_streak = v_maior, ultimo_acesso = v_hoje, updated_at = NOW()
        WHERE user_id = v_user_id;
    ELSE
        v_atual := 1;
        v_maior := GREATEST(v_maior, 1);
        UPDATE public.streaks
        SET streak_atual = 1, maior_streak = v_maior, ultimo_acesso = v_hoje, updated_at = NOW()
        WHERE user_id = v_user_id;
    END IF;

    IF v_atual >= 7 THEN
        PERFORM public.conceder_conquista(v_user_id, 'sequencia_7_dias');
    END IF;

    RETURN jsonb_build_object('streak_atual', v_atual, 'maior_streak', v_maior);
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;


