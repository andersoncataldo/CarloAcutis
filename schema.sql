$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp;

-- Nova RPC: permite que o CRIADOR de uma liga recupere o código de acesso
-- para compartilhar de novo (ex: perdeu a mensagem original). Não expõe o
-- código a outros membros — ver seção 4 abaixo sobre por que a tabela
-- ligas deixa de expor essa coluna por SELECT direto.
CREATE OR REPLACE FUNCTION public.obter_minha_liga_codigo()
RETURNS JSONB AS $$
DECLARE
    v_user_id UUID;
    v_codigo VARCHAR;
BEGIN
    v_user_id := auth.uid();
    IF v_user_id IS NULL THEN
        RAISE EXCEPTION 'Usuário não autenticado.';
    END IF;

    SELECT l.codigo_acesso INTO v_codigo
    FROM public.ligas l
    JOIN public.profiles p ON p.liga_id = l.id
    WHERE p.id = v_user_id AND l.criado_por = v_user_id;

    IF v_codigo IS NULL THEN
        RETURN NULL;
    END IF;

    RETURN jsonb_build_object('codigo_acesso', v_codigo);
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp;


-- =================================================================
-- 2. PROFILES: RESTRINGE LEITURA AO PRÓPRIO DONO + VIEW DE RANKING
-- -----------------------------------------------------------------
-- A policy anterior ("Leitura de Profiles permitida para autenticados",
-- USING (true)) permitia que QUALQUER usuário autenticado lesse a tabela
-- profiles inteira — inclusive a coluna email de todo mundo — bastando
-- chamar supabase.from('profiles').select('*') pelo DevTools. O ranking
-- precisa mostrar nome/xp/nivel de outras pessoas, mas não precisa (e não
-- deve) expor e-mail. Solução: profiles fica restrito ao próprio dono, e
-- uma view separada expõe só as colunas seguras para todo mundo.
-- =================================================================
DROP POLICY IF EXISTS "Leitura de Profiles permitida para autenticados" ON public.profiles;
DROP POLICY IF EXISTS "Leitura do próprio Profile" ON public.profiles;
CREATE POLICY "Leitura do próprio Profile"
    ON public.profiles FOR SELECT
    TO authenticated USING (auth.uid() = id);

-- View pública de ranking: como é criada pelo role que roda esta migração
-- (tipicamente "postgres", que ignora RLS), ela consegue ler todas as
-- linhas de profiles mesmo com a policy acima restringindo ao próprio
-- dono — e reexpõe apenas as colunas não sensíveis.
CREATE OR REPLACE VIEW public.ranking_publico AS
SELECT id, nome, xp, nivel, liga_id
FROM public.profiles;

GRANT SELECT ON public.ranking_publico TO anon, authenticated;


-- =================================================================
-- 3. USUARIO_CONQUISTAS: RESTRINGE AO PRÓPRIO USUÁRIO
-- -----------------------------------------------------------------
-- Não há necessidade de produto comprovada para expor as conquistas de
-- outros usuários publicamente ainda, então fechamos por padrão. Se no
-- futuro quiser mostrar "medalhas" no ranking de liga, isso pode virar
-- outra view pública restrita a colunas específicas, como fizemos acima.
-- =================================================================
DROP POLICY IF EXISTS "Leitura de Conquistas de Usuários" ON public.usuario_conquistas;
CREATE POLICY "Leitura de Conquistas de Usuários"
    ON public.usuario_conquistas FOR SELECT
    TO authenticated USING (auth.uid() = user_id);


-- =================================================================
-- 4. LIGAS: ESCONDE codigo_acesso DA LEITURA DIRETA E TRAVA INSERT
-- -----------------------------------------------------------------
-- Antes, qualquer autenticado podia SELECT * FROM ligas e ver o
-- codigo_acesso de TODAS as ligas (o convite/senha de entrada), e também
-- podia fazer INSERT direto na tabela via PostgREST, contornando o limite
-- de 3 ligas por usuário que só existe dentro da RPC criar_liga.
-- =================================================================
REVOKE SELECT ON public.ligas FROM authenticated, anon;
GRANT SELECT (id, nome, criado_por, created_at) ON public.ligas TO authenticated;

REVOKE INSERT ON public.ligas FROM authenticated;
DROP POLICY IF EXISTS "Criação de Ligas permitida para autenticados" ON public.ligas;
-- (sem policy de INSERT para authenticated: toda criação de liga passa
-- exclusivamente pela RPC criar_liga, que roda como SECURITY DEFINER)


-- =================================================================
-- 5. CONSTRAINTS DE INTEGRIDADE
-- =================================================================
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'profiles_xp_nao_negativo') THEN
        ALTER TABLE public.profiles ADD CONSTRAINT profiles_xp_nao_negativo CHECK (xp >= 0);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'profiles_nome_nao_vazio') THEN
        ALTER TABLE public.profiles ADD CONSTRAINT profiles_nome_nao_vazio CHECK (LENGTH(TRIM(nome)) > 0);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ligas_nome_nao_vazio') THEN
        ALTER TABLE public.ligas ADD CONSTRAINT ligas_nome_nao_vazio CHECK (LENGTH(TRIM(nome)) > 0);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ligas_codigo_formato') THEN
        ALTER TABLE public.ligas ADD CONSTRAINT ligas_codigo_formato CHECK (codigo_acesso ~ '^[A-Z0-9]{6,10}$');
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'perguntas_resposta_valida') THEN
        ALTER TABLE public.perguntas ADD CONSTRAINT perguntas_resposta_valida CHECK (resposta_correta IN ('A', 'B', 'C', 'D'));
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'perguntas_textos_nao_vazios') THEN
        ALTER TABLE public.perguntas ADD CONSTRAINT perguntas_textos_nao_vazios CHECK (
            LENGTH(TRIM(texto_pergunta)) > 0 AND
            LENGTH(TRIM(opcao_a)) > 0 AND LENGTH(TRIM(opcao_b)) > 0 AND
            LENGTH(TRIM(opcao_c)) > 0 AND LENGTH(TRIM(opcao_d)) > 0
        );
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'temporadas_titulo_nao_vazio') THEN
        ALTER TABLE public.temporadas ADD CONSTRAINT temporadas_titulo_nao_vazio CHECK (LENGTH(TRIM(titulo)) > 0);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'temporadas_ordem_nao_negativa') THEN
        ALTER TABLE public.temporadas ADD CONSTRAINT temporadas_ordem_nao_negativa CHECK (ordem IS NULL OR ordem >= 0);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'perguntas_ordem_nao_negativa') THEN
        ALTER TABLE public.perguntas ADD CONSTRAINT perguntas_ordem_nao_negativa CHECK (ordem IS NULL OR ordem >= 0);
    END IF;
END $$;

-- NOTA sobre "uma única temporada ativa": decidimos NÃO forçar essa regra
-- no banco, porque é uma decisão de produto, não uma invariante técnica —
-- pode fazer sentido rodar duas temporadas em paralelo (ex: "Advento" e
-- "Vidas de Santos" ao mesmo tempo). Se um dia isso virar regra de
-- negócio obrigatória, um índice único parcial resolve:
--   CREATE UNIQUE INDEX temporadas_unica_ativa ON public.temporadas ((true)) WHERE ativa;
-- (garante no máximo 1 linha com ativa = true no banco inteiro).

-- NOTA sobre "impedir múltiplas ligas simultâneas por usuário": já é
-- garantido pelo modelo de dados — profiles.liga_id é uma FK única por
-- linha (um usuário só pode apontar para uma liga por vez), não uma
-- tabela de associação N:N.


-- =================================================================
-- 6. TABELA DE AUDITORIA ADMINISTRATIVA
-- -----------------------------------------------------------------
-- Loga automaticamente (via trigger) toda alteração em temporadas,
-- perguntas e mudanças de role em profiles — não depende de nenhuma tela
-- específica do admin lembrar de chamar uma função de log.
-- =================================================================
CREATE TABLE IF NOT EXISTS public.auditoria_admin (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    acao VARCHAR(20) NOT NULL,
    entidade VARCHAR(50) NOT NULL,
    entidade_id TEXT,
    valores_antigos JSONB,
    valores_novos JSONB,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_auditoria_admin_created_at ON public.auditoria_admin(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_auditoria_admin_entidade ON public.auditoria_admin(entidade, entidade_id);

ALTER TABLE public.auditoria_admin ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Somente admin lê auditoria" ON public.auditoria_admin;
CREATE POLICY "Somente admin lê auditoria"
    ON public.auditoria_admin FOR SELECT
    TO authenticated USING (public.is_admin());

GRANT SELECT ON public.auditoria_admin TO authenticated;
-- Sem GRANT de INSERT/UPDATE/DELETE para authenticated: só a trigger
-- abaixo (rodando como SECURITY DEFINER, dono postgres) grava aqui.

CREATE OR REPLACE FUNCTION public.registrar_auditoria()
RETURNS TRIGGER AS $$
BEGIN
    INSERT INTO public.auditoria_admin (admin_id, acao, entidade, entidade_id, valores_antigos, valores_novos)
    VALUES (
        auth.uid(),
        TG_OP,
        TG_TABLE_NAME,
        COALESCE(NEW.id::TEXT, OLD.id::TEXT),
        CASE WHEN TG_OP IN ('UPDATE', 'DELETE') THEN to_jsonb(OLD) ELSE NULL END,
        CASE WHEN TG_OP IN ('UPDATE', 'INSERT') THEN to_jsonb(NEW) ELSE NULL END
    );
    RETURN COALESCE(NEW, OLD);
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp;

DROP TRIGGER IF EXISTS audit_temporadas ON public.temporadas;
CREATE TRIGGER audit_temporadas
    AFTER INSERT OR UPDATE OR DELETE ON public.temporadas
    FOR EACH ROW EXECUTE FUNCTION public.registrar_auditoria();

DROP TRIGGER IF EXISTS audit_perguntas ON public.perguntas;
CREATE TRIGGER audit_perguntas
    AFTER INSERT OR UPDATE OR DELETE ON public.perguntas
    FOR EACH ROW EXECUTE FUNCTION public.registrar_auditoria();

DROP TRIGGER IF EXISTS audit_profiles_role ON public.profiles;
CREATE TRIGGER audit_profiles_role
    AFTER UPDATE OF role ON public.profiles
    FOR EACH ROW
    WHEN (OLD.role IS DISTINCT FROM NEW.role)
    EXECUTE FUNCTION public.registrar_auditoria();


-- =================================================================
-- 7. REMOVE OS DEFAULT PRIVILEGES EXCESSIVAMENTE PERMISSIVOS
-- -----------------------------------------------------------------
-- O script original fazia toda tabela FUTURA herdar automaticamente
-- SELECT/INSERT/UPDATE/DELETE para "authenticated" e SELECT para "anon",
-- independente de RLS estar correta para ela. Revertendo isso força que
-- toda tabela nova passe por uma decisão explícita de GRANT, como as que
-- fizemos aqui para streaks/conquistas/auditoria_admin.
-- =================================================================
ALTER DEFAULT PRIVILEGES IN SCHEMA public
    REVOKE SELECT, INSERT, UPDATE, DELETE ON TABLES FROM authenticated;
ALTER DEFAULT PRIVILEGES IN SCHEMA public
    REVOKE SELECT ON TABLES FROM anon;

