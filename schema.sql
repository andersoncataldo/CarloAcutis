-- Enable UUID Extension if not enabled
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- 1. TABELA DE LIGAS PAROQUIAIS
CREATE TABLE IF NOT EXISTS public.ligas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    codigo_acesso VARCHAR(20) NOT NULL UNIQUE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. TABELA DE PROFILES (ESTENDE AUTH.USERS)
CREATE TABLE IF NOT EXISTS public.profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    nome VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    xp INT NOT NULL DEFAULT 0,
    nivel VARCHAR(100) NOT NULL DEFAULT 'Peregrino',
    liga_id BIGINT REFERENCES public.ligas(id) ON DELETE SET NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3. TABELA DE TEMPORADAS DO QUIZ
--    GENERATED BY DEFAULT permite forçar IDs fixos no seed data,
--    garantindo a idempotência real do ON CONFLICT (id) DO NOTHING.
CREATE TABLE IF NOT EXISTS public.temporadas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(255) NOT NULL,
    descricao TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 4. TABELA DE PERGUNTAS DO QUIZ
--    CHAR(1) em resposta_correta: valor sempre será 'A','B','C' ou 'D'.
--    Mais preciso e eficiente que VARCHAR(5).
--    GENERATED BY DEFAULT para permitir IDs fixos no seed data.
CREATE TABLE IF NOT EXISTS public.perguntas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    temporada_id BIGINT NOT NULL REFERENCES public.temporadas(id) ON DELETE CASCADE,
    texto_pergunta TEXT NOT NULL,
    opcao_a TEXT NOT NULL,
    opcao_b TEXT NOT NULL,
    opcao_c TEXT NOT NULL,
    opcao_d TEXT NOT NULL,
    resposta_correta CHAR(1) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 5. TABELA DE HISTORICO DE RESPOSTAS DO USUARIO (EVITA XP REPETIDO)
CREATE TABLE IF NOT EXISTS public.respostas_usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    pergunta_id BIGINT NOT NULL REFERENCES public.perguntas(id) ON DELETE CASCADE,
    acertou BOOLEAN NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    CONSTRAINT unique_user_pergunta UNIQUE (user_id, pergunta_id)
);

-- =================================================================
-- CORRECAO DE COLUNAS IDENTITY EM TABELAS JA EXISTENTES
-- -----------------------------------------------------------------
-- Se as tabelas já existiam com GENERATED ALWAYS, o CREATE TABLE IF NOT
-- EXISTS acima não as recria. Os comandos abaixo garantem que todas as
-- colunas identity usem BY DEFAULT, permitindo IDs explícitos no seed.
-- =================================================================
ALTER TABLE IF EXISTS public.ligas              ALTER COLUMN id SET GENERATED BY DEFAULT;
ALTER TABLE IF EXISTS public.temporadas         ALTER COLUMN id SET GENERATED BY DEFAULT;
ALTER TABLE IF EXISTS public.perguntas          ALTER COLUMN id SET GENERATED BY DEFAULT;
ALTER TABLE IF EXISTS public.respostas_usuario  ALTER COLUMN id SET GENERATED BY DEFAULT;

-- =================================================================
-- INDICES DE PERFORMANCE EM CHAVES ESTRANGEIRAS
-- -----------------------------------------------------------------
-- O PostgreSQL NÃO cria índices automaticamente em FKs.
-- Sem esses índices, JOINs e filtros por liga/temporada fazem
-- varreduras sequenciais (seq scan), ficando muito lentos com volume.
-- =================================================================

-- Melhora performance ao filtrar profiles por liga (ranking da liga, etc.)
CREATE INDEX IF NOT EXISTS idx_profiles_liga_id ON public.profiles(liga_id);

-- Melhora performance ao buscar perguntas de uma temporada específica
CREATE INDEX IF NOT EXISTS idx_perguntas_temporada_id ON public.perguntas(temporada_id);

-- Melhora performance ao buscar histórico de respostas de um usuário
-- (complementa a UNIQUE constraint que já cobre buscas por user_id + pergunta_id)
CREATE INDEX IF NOT EXISTS idx_respostas_user_id ON public.respostas_usuario(user_id);

-- =================================================================
-- TRIGGER PARA CRIAR PROFILE AUTOMATICAMENTE QUANDO UM USUARIO SE REGISTRA
-- =================================================================
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
BEGIN
    INSERT INTO public.profiles (id, nome, email, xp, nivel)
    VALUES (
        NEW.id,
        COALESCE(NEW.raw_user_meta_data->>'nome', 'Peregrino'),
        NEW.email,
        0,
        'Peregrino'
    );
    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Drop trigger if exists to prevent duplication
DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
    AFTER INSERT ON auth.users
    FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

-- =================================================================
-- FUNCTION RPC PARA CALCULAR TITULO / NIVEL BASEADO NO XP
-- =================================================================
CREATE OR REPLACE FUNCTION public.calcular_titulo(xp_total INT)
RETURNS VARCHAR AS $$
DECLARE
    nivel_num INT;
BEGIN
    nivel_num := (xp_total / 1000) + 1;
    IF nivel_num < 5 THEN
        RETURN 'Peregrino';
    ELSIF nivel_num < 10 THEN
        RETURN 'Discípulo';
    ELSIF nivel_num < 20 THEN
        RETURN 'Missionário';
    ELSIF nivel_num < 50 THEN
        RETURN 'Apóstolo Digital';
    ELSE
        RETURN 'Ciberapóstolo da Eucaristia';
    END IF;
END;
$$ LANGUAGE plpgsql IMMUTABLE;

-- =================================================================
-- FUNCTION RPC PARA RESPONDER PERGUNTA COM SEGURANCA NO BANCO
-- -----------------------------------------------------------------
-- Esta função roda como SECURITY DEFINER (com permissões de admin),
-- portanto o usuário nunca precisa de acesso direto de UPDATE em xp/nivel.
-- O parâmetro é CHAR(1) pois a resposta sempre será 'A', 'B', 'C' ou 'D'.
-- =================================================================
CREATE OR REPLACE FUNCTION public.responder_pergunta(
    p_pergunta_id BIGINT,
    p_resposta_selecionada CHAR(1)
)
RETURNS JSONB AS $$
DECLARE
    v_user_id UUID;
    v_resposta_correta CHAR(1);
    v_is_correct BOOLEAN := FALSE;
    v_ja_respondida BOOLEAN := FALSE;
    v_new_xp INT;
    v_new_nivel VARCHAR;
BEGIN
    v_user_id := auth.uid();
    IF v_user_id IS NULL THEN
        RAISE EXCEPTION 'Usuário não autenticado.';
    END IF;

    SELECT resposta_correta INTO v_resposta_correta
    FROM public.perguntas
    WHERE id = p_pergunta_id;

    IF v_resposta_correta IS NULL THEN
        RAISE EXCEPTION 'Pergunta não encontrada.';
    END IF;

    -- Verifica se o usuário já respondeu a esta pergunta antes
    SELECT EXISTS (
        SELECT 1
        FROM public.respostas_usuario
        WHERE user_id = v_user_id
          AND pergunta_id = p_pergunta_id
    ) INTO v_ja_respondida;

    IF UPPER(v_resposta_correta) = UPPER(p_resposta_selecionada) THEN
        v_is_correct := TRUE;
    END IF;

    IF NOT v_ja_respondida THEN
        -- Registra a resposta no histórico do usuário
        INSERT INTO public.respostas_usuario (user_id, pergunta_id, acertou)
        VALUES (v_user_id, p_pergunta_id, v_is_correct);

        -- Concede XP apenas se for a primeira vez e a resposta for correta
        IF v_is_correct THEN
            UPDATE public.profiles
            SET xp = xp + 100,
                nivel = public.calcular_titulo(xp + 100),
                updated_at = NOW()
            WHERE id = v_user_id
            RETURNING xp, nivel INTO v_new_xp, v_new_nivel;
        ELSE
            SELECT xp, nivel INTO v_new_xp, v_new_nivel
            FROM public.profiles
            WHERE id = v_user_id;
        END IF;
    ELSE
        -- Usuário já respondeu anteriormente (não soma XP novamente)
        SELECT xp, nivel INTO v_new_xp, v_new_nivel
        FROM public.profiles
        WHERE id = v_user_id;
    END IF;

    RETURN jsonb_build_object(
        'correct', v_is_correct,
        'xp', v_new_xp,
        'nivel', v_new_nivel,
        'first_attempt', NOT v_ja_respondida
    );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- =================================================================
-- FUNCTION RPC PARA CRIAR UMA LIGA PAROQUIAL COM SEGURANÇA
-- -----------------------------------------------------------------
-- Roda como SECURITY DEFINER para poder atualizar liga_id em profiles
-- sem expor permissão de UPDATE direta ao usuário.
-- =================================================================
CREATE OR REPLACE FUNCTION public.criar_liga(p_nome TEXT)
RETURNS JSONB AS $$
DECLARE
    v_user_id UUID;
    v_codigo TEXT;
    v_nova_liga_id BIGINT;
    v_liga_nome VARCHAR;
    v_liga_codigo VARCHAR;
BEGIN
    v_user_id := auth.uid();
    IF v_user_id IS NULL THEN
        RAISE EXCEPTION 'Usuário não autenticado.';
    END IF;

    IF TRIM(p_nome) = '' THEN
        RAISE EXCEPTION 'Nome da liga não pode ser vazio.';
    END IF;

    -- Gera código de acesso único de 8 caracteres alfanuméricos (maiúsculos)
    v_codigo := UPPER(SUBSTRING(MD5(RANDOM()::TEXT || CLOCK_TIMESTAMP()::TEXT) FROM 1 FOR 8));

    INSERT INTO public.ligas (nome, codigo_acesso)
    VALUES (TRIM(p_nome), v_codigo)
    RETURNING id, nome, codigo_acesso INTO v_nova_liga_id, v_liga_nome, v_liga_codigo;

    -- Vincula o usuário à nova liga de forma segura (sem UPDATE direto no front)
    UPDATE public.profiles
    SET liga_id = v_nova_liga_id,
        updated_at = NOW()
    WHERE id = v_user_id;

    RETURN jsonb_build_object(
        'liga_id', v_nova_liga_id,
        'nome', v_liga_nome,
        'codigo_acesso', v_liga_codigo
    );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- =================================================================
-- FUNCTION RPC PARA ENTRAR EM UMA LIGA PAROQUIAL COM SEGURANÇA
-- -----------------------------------------------------------------
-- Roda como SECURITY DEFINER para poder atualizar liga_id em profiles
-- sem expor permissão de UPDATE direta ao usuário.
-- =================================================================
CREATE OR REPLACE FUNCTION public.entrar_liga(p_codigo TEXT)
RETURNS JSONB AS $$
DECLARE
    v_user_id UUID;
    v_liga_id BIGINT;
    v_liga_nome VARCHAR;
    v_liga_codigo VARCHAR;
BEGIN
    v_user_id := auth.uid();
    IF v_user_id IS NULL THEN
        RAISE EXCEPTION 'Usuário não autenticado.';
    END IF;

    -- Busca liga pelo código (case-insensitive via UPPER)
    SELECT id, nome, codigo_acesso INTO v_liga_id, v_liga_nome, v_liga_codigo
    FROM public.ligas
    WHERE UPPER(codigo_acesso) = UPPER(TRIM(p_codigo));

    IF v_liga_id IS NULL THEN
        RAISE EXCEPTION 'Código de liga inválido ou não encontrado.';
    END IF;

    -- Vincula o usuário à liga de forma segura (sem UPDATE direto no front)
    UPDATE public.profiles
    SET liga_id = v_liga_id,
        updated_at = NOW()
    WHERE id = v_user_id;

    RETURN jsonb_build_object(
        'liga_id', v_liga_id,
        'nome', v_liga_nome,
        'codigo_acesso', v_liga_codigo
    );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- =================================================================
-- FUNCTION RPC PARA SAIR DE UMA LIGA PAROQUIAL COM SEGURANÇA
-- -----------------------------------------------------------------
-- Permite que o usuário deixe a liga atual definindo liga_id como NULL.
-- =================================================================
CREATE OR REPLACE FUNCTION public.sair_liga()
RETURNS JSONB AS $$
DECLARE
    v_user_id UUID;
BEGIN
    v_user_id := auth.uid();
    IF v_user_id IS NULL THEN
        RAISE EXCEPTION 'Usuário não autenticado.';
    END IF;

    -- Desvincula o usuário da liga (seta NULL)
    UPDATE public.profiles
    SET liga_id = NULL,
        updated_at = NOW()
    WHERE id = v_user_id;

    RETURN jsonb_build_object('success', true);
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

