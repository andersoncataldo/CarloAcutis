-- GRANTS DE PRIVILÉGIO NAS TABELAS (NECESSÁRIO ALÉM DA RLS!)
-- -----------------------------------------------------------------
-- O RLS filtra QUAIS LINHAS um role pode ver/alterar, mas antes disso
-- o Postgres exige que o role tenha o GRANT básico na tabela. Sem essas
-- linhas abaixo, mesmo com as policies certas, o PostgREST retorna
-- erro 403 (permission denied) em vez de aplicar a policy.
-- =================================================================
GRANT SELECT ON public.profiles TO authenticated;

-- SEGURANÇA: Revoga UPDATE geral da tabela profiles.
-- Apenas a coluna `nome` pode ser atualizada diretamente pelo usuário.
-- Colunas `xp`, `nivel` e `liga_id` são gerenciadas exclusivamente
-- pelas RPCs com SECURITY DEFINER (responder_pergunta, criar_liga, entrar_liga).
REVOKE UPDATE ON public.profiles FROM authenticated;
GRANT UPDATE (nome) ON public.profiles TO authenticated;

GRANT SELECT, INSERT ON public.ligas TO authenticated;
GRANT SELECT ON public.temporadas TO anon, authenticated;
GRANT SELECT ON public.perguntas TO anon, authenticated;
GRANT SELECT ON public.respostas_usuario TO authenticated;

-- Garante acesso às sequences por trás dos IDs GENERATED AS IDENTITY
-- (necessário para os INSERTs liberados por policy, ex: criação de ligas)
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO authenticated;

-- Garante que tabelas criadas no futuro já herdem essas permissões
-- automaticamente, evitando repetir esse problema depois
ALTER DEFAULT PRIVILEGES IN SCHEMA public
    GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO authenticated;
ALTER DEFAULT PRIVILEGES IN SCHEMA public
    GRANT SELECT ON TABLES TO anon;

