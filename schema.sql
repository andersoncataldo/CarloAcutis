-- responder_pergunta: adiciona "SET search_path" e passa a rejeitar
-- explicitamente perguntas desativadas ou de temporadas desativadas —
-- antes, só o filtro do frontend (.eq('ativa', true)) impedia isso, o que
-- não é proteção real (qualquer um pode chamar a RPC direto passando o id
-- de uma pergunta arquivada).
CREATE OR REPLACE FUNCTION public.responder_pergunta(
    p_pergunta_id BIGINT,
    p_resposta_selecionada CHAR(1)
)
RETURNS JSONB AS $$
DECLARE
    v_user_id UUID;
    v_resposta_correta CHAR(1);
    v_temporada_id BIGINT;
    v_pergunta_ativa BOOLEAN;
    v_temporada_ativa BOOLEAN;
    v_is_correct BOOLEAN := FALSE;
    v_ja_respondida BOOLEAN := FALSE;
    v_new_xp INT;
    v_new_nivel VARCHAR;
    v_total_perguntas INT;
    v_total_respondidas INT;
BEGIN
    v_user_id := auth.uid();
    IF v_user_id IS NULL THEN
        RAISE EXCEPTION 'Usuário não autenticado.';
    END IF;

    IF UPPER(p_resposta_selecionada) NOT IN ('A', 'B', 'C', 'D') THEN
        RAISE EXCEPTION 'Resposta inválida. Use A, B, C ou D.';
    END IF;

    SELECT p.resposta_correta, p.temporada_id, p.ativa, t.ativa
    INTO v_resposta_correta, v_temporada_id, v_pergunta_ativa, v_temporada_ativa
    FROM public.perguntas p
    JOIN public.temporadas t ON t.id = p.temporada_id
    WHERE p.id = p_pergunta_id;

    IF v_resposta_correta IS NULL THEN
        RAISE EXCEPTION 'Pergunta não encontrada.';
    END IF;

    IF NOT v_pergunta_ativa OR NOT v_temporada_ativa THEN
        RAISE EXCEPTION 'Esta pergunta não está mais disponível.';
    END IF;

    SELECT EXISTS (
        SELECT 1
        FROM public.respostas_usuario
        WHERE user_id = v_user_id
          AND pergunta_id = p_pergunta_id
    ) INTO v_ja_respondida;

    IF UPPER(v_resposta_correta) = UPPER(p_resposta_selecionada) THEN
        v_is_correct := TRUE;
    END IF;

    IF NOT v_ja_respondida THEN
        INSERT INTO public.respostas_usuario (user_id, pergunta_id, acertou)
        VALUES (v_user_id, p_pergunta_id, v_is_correct);

        IF v_is_correct THEN
            UPDATE public.profiles
            SET xp = xp + 100,
                updated_at = NOW()
            WHERE id = v_user_id
            RETURNING xp, nivel INTO v_new_xp, v_new_nivel;

            PERFORM public.conceder_conquista(v_user_id, 'primeira_resposta');

            SELECT COUNT(*) INTO v_total_perguntas
            FROM public.perguntas WHERE temporada_id = v_temporada_id AND ativa = true;

            SELECT COUNT(*) INTO v_total_respondidas
            FROM public.respostas_usuario ru
            JOIN public.perguntas p ON p.id = ru.pergunta_id
            WHERE ru.user_id = v_user_id AND p.temporada_id = v_temporada_id AND p.ativa = true;

            IF v_total_perguntas > 0 AND v_total_respondidas >= v_total_perguntas THEN
                PERFORM public.conceder_conquista(v_user_id, 'temporada_completa');
            END IF;
        ELSE
            SELECT xp, nivel INTO v_new_xp, v_new_nivel
            FROM public.profiles
            WHERE id = v_user_id;
        END IF;
    ELSE
        SELECT xp, nivel INTO v_new_xp, v_new_nivel
        FROM public.profiles
        WHERE id = v_user_id;
    END IF;

    RETURN jsonb_build_object(
        'correct', v_is_correct,
        'xp', v_new_xp,
        'nivel', v_new_nivel,
        'first_attempt', NOT v_ja_respondida
    );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp;

CREATE OR REPLACE FUNCTION public.criar_liga(p_nome TEXT)
RETURNS JSONB AS $$
DECLARE
    v_user_id UUID;
    v_codigo TEXT;
    v_nova_liga_id BIGINT;
    v_liga_nome VARCHAR;
    v_liga_codigo VARCHAR;
    v_ligas_criadas INT;
BEGIN
    v_user_id := auth.uid();
    IF v_user_id IS NULL THEN
        RAISE EXCEPTION 'Usuário não autenticado.';
    END IF;

    IF TRIM(p_nome) = '' THEN
        RAISE EXCEPTION 'Nome da liga não pode ser vazio.';
    END IF;

    IF LENGTH(TRIM(p_nome)) > 100 THEN
        RAISE EXCEPTION 'Nome da liga muito longo (máximo 100 caracteres).';
    END IF;

    SELECT COUNT(*) INTO v_ligas_criadas FROM public.ligas WHERE criado_por = v_user_id;
    IF v_ligas_criadas >= 3 THEN
        RAISE EXCEPTION 'Você já atingiu o limite de 3 ligas criadas por usuário.';
    END IF;

    v_codigo := UPPER(SUBSTRING(MD5(RANDOM()::TEXT || CLOCK_TIMESTAMP()::TEXT) FROM 1 FOR 8));

    INSERT INTO public.ligas (nome, codigo_acesso, criado_por)
    VALUES (TRIM(p_nome), v_codigo, v_user_id)
    RETURNING id, nome, codigo_acesso INTO v_nova_liga_id, v_liga_nome, v_liga_codigo;

    UPDATE public.profiles
    SET liga_id = v_nova_liga_id,
        updated_at = NOW()
    WHERE id = v_user_id;

    PERFORM public.conceder_conquista(v_user_id, 'fundador_liga');

    RETURN jsonb_build_object(
        'liga_id', v_nova_liga_id,
        'nome', v_liga_nome,
        'codigo_acesso', v_liga_codigo
    );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp;

CREATE OR REPLACE FUNCTION public.entrar_liga(p_codigo TEXT)
RETURNS JSONB AS $$
DECLARE
    v_user_id UUID;
    v_liga_id BIGINT;
    v_liga_nome VARCHAR;
    v_liga_codigo VARCHAR;
BEGIN
    v_user_id := auth.uid();
    IF v_user_id IS NULL THEN
        RAISE EXCEPTION 'Usuário não autenticado.';
    END IF;

    SELECT id, nome, codigo_acesso INTO v_liga_id, v_liga_nome, v_liga_codigo
    FROM public.ligas
    WHERE UPPER(codigo_acesso) = UPPER(TRIM(p_codigo));

    IF v_liga_id IS NULL THEN
        RAISE EXCEPTION 'Código de liga inválido ou não encontrado.';
    END IF;

    UPDATE public.profiles
    SET liga_id = v_liga_id,
        updated_at = NOW()
    WHERE id = v_user_id;

    PERFORM public.conceder_conquista(v_user_id, 'entrou_liga');

    RETURN jsonb_build_object(
        'liga_id', v_liga_id,
        'nome', v_liga_nome,
        'codigo_acesso', v_liga_codigo
    );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp;

CREATE OR REPLACE FUNCTION public.sair_liga()
RETURNS JSONB AS $$
DECLARE
    v_user_id UUID;
BEGIN
    v_user_id := auth.uid();
    IF v_user_id IS NULL THEN
        RAISE EXCEPTION 'Usuário não autenticado.';
    END IF;

    UPDATE public.profiles
    SET liga_id = NULL,
        updated_at = NOW()
